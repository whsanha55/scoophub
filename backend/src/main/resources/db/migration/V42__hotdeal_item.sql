-- V42: 핫딜 수집 원본 (#271, feedforge raw_item 이관)
-- crawl_data(JSON) 대신 전용 테이블 — 중복 제거·재평가·피드백 연결에 컬럼과 제약이 필요하다.

CREATE TABLE hotdeal_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source        TEXT NOT NULL,                       -- ZOD | PPOMPPU
    provider      TEXT NOT NULL,                       -- 실제 공급자 (없으면 소스명). 고유 제약에 NULL 금지
    source_key    TEXT NOT NULL,
    category      TEXT,
    title         TEXT NOT NULL,
    url           TEXT NOT NULL,
    canonical_url TEXT,
    extra         JSONB NOT NULL DEFAULT '{}'::jsonb,  -- 가격·몰·추천수 등 재수집 시 갱신되는 메타데이터
    item_at       TIMESTAMPTZ NOT NULL,                -- 원본 게시 시각
    availability  TEXT NOT NULL DEFAULT 'UNKNOWN'
        CONSTRAINT hotdeal_item_availability_check CHECK (availability IN ('UNKNOWN', 'AVAILABLE', 'ENDED')),
    first_seen_at TIMESTAMPTZ NOT NULL,
    last_seen_at  TIMESTAMPTZ NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_hotdeal_item_source UNIQUE (source, provider, source_key)
);

-- 스코어링·재평가 대상(신선도 기간 내 게시물) 조회
CREATE INDEX idx_hotdeal_item_item_at ON hotdeal_item (item_at DESC);

-- 알구더는 Cloudflare 봇 차단(403)으로 꺼 둔다. 차단이 풀리면 crawl_schedule 에서 켠다.
INSERT INTO crawl_schedule (crawler, job_id, schedule_type, schedule_minutes, enabled, description) VALUES
    ('hotdeal_zod', 'hotdeal_zod_crawler', 'interval', 30, FALSE, '알구더 핫딜 크롤 (차단으로 중지)')
ON CONFLICT (crawler, job_id) DO NOTHING;
