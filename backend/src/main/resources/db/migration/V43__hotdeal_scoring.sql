CREATE TABLE hotdeal_interest_profile (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind           TEXT NOT NULL
        CONSTRAINT hotdeal_interest_profile_kind_check CHECK (kind IN ('KEYWORD', 'CATEGORY', 'SOURCE')),
    value          TEXT NOT NULL,
    seed_weight    DOUBLE PRECISION NOT NULL,          -- 수동 설정 기준값
    learned_weight DOUBLE PRECISION NOT NULL DEFAULT 0, -- 피드백에 의한 변화량
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_hotdeal_interest_profile UNIQUE (kind, value)
);

CREATE TABLE hotdeal_feed_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotdeal_item_id BIGINT NOT NULL REFERENCES hotdeal_item (id),
    score           DOUBLE PRECISION NOT NULL,
    matched_terms   JSONB NOT NULL,                    -- 추천 이유·매칭 항목·당시 가중치·인기 보너스
    popular         BOOLEAN NOT NULL,                  -- 콜드스타트 인기 노출 여부
    scoring_version TEXT NOT NULL,
    recommended_at  TIMESTAMPTZ NOT NULL,
    evaluated_at    TIMESTAMPTZ NOT NULL,
    expires_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_hotdeal_feed_item UNIQUE (hotdeal_item_id)
);

CREATE INDEX idx_hotdeal_feed_item_score ON hotdeal_feed_item (score DESC);
