-- 재평가에서 추천 조건을 벗어난 항목은 삭제하지 않고 기본 피드에서만 숨긴다 (HOTDEAL_PLAN 8.5)
ALTER TABLE hotdeal_feed_item ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;

-- 현재 피드백 상태 (항목당 1건). 취소하면 행을 지운다
CREATE TABLE hotdeal_feedback (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotdeal_feed_item_id BIGINT NOT NULL REFERENCES hotdeal_feed_item (id),
    kind                 TEXT NOT NULL
        CONSTRAINT hotdeal_feedback_kind_check CHECK (kind IN ('LIKE', 'DISLIKE')),
    channel              TEXT NOT NULL
        CONSTRAINT hotdeal_feedback_channel_check CHECK (channel IN ('WEB', 'TELEGRAM')),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_hotdeal_feedback UNIQUE (hotdeal_feed_item_id)
);

-- 피드백 변경과 학습 이력. 한 번의 변경(event)에서 프로필 항목마다 1행, 매칭 항목이 없으면 profile_id NULL 1행.
-- delta 는 상·하한을 반영해 실제로 적용된 변화량이다. 항목별 delta 합이 그 항목 피드백의 현재 학습 효과다.
CREATE TABLE hotdeal_feedback_log (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_event_id    UUID NOT NULL,
    hotdeal_feed_item_id BIGINT NOT NULL REFERENCES hotdeal_feed_item (id),
    profile_id           BIGINT REFERENCES hotdeal_interest_profile (id) ON DELETE SET NULL,
    previous_kind        TEXT,
    new_kind             TEXT,
    delta                DOUBLE PRECISION NOT NULL,
    previous_weight      DOUBLE PRECISION,
    new_weight           DOUBLE PRECISION,
    reason               TEXT NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_hotdeal_feedback_log UNIQUE (feedback_event_id, profile_id)
);

CREATE INDEX idx_hotdeal_feedback_log_feed_item ON hotdeal_feedback_log (hotdeal_feed_item_id);
